const WORDMARK_VIEWBOX_WIDTH = 750
const WORDMARK_VIEWBOX_HEIGHT = 102

/** Left-to-right fallback used before the paths have been measured. */
const WORDMARK_GLYPHS_FALLBACK: number[][] = [
  [0],
  [3],
  [1],
  [5],
  [4],
  [7],
  [8, 9],
  [6],
  [2],
]

export const WORDMARK_GLYPH_COUNT = WORDMARK_GLYPHS_FALLBACK.length

interface Box {
  x: number
  width: number
}

/** Paths whose horizontal bounds overlap are one letter (the i stem and dot). */
export function groupWordmarkGlyphs(boxes: Box[]): number[][] {
  const order = boxes
    .map((box, index) => ({ index, x: box.x, right: box.x + box.width }))
    .sort((a, b) => a.x - b.x || a.index - b.index)
  const groups: number[][] = []
  for (const item of order) {
    const current = groups[groups.length - 1]
    if (!current) {
      groups.push([item.index])
      continue
    }
    const previous = boxes[current[current.length - 1]]
    const overlaps = item.x < previous.x + previous.width
    if (overlaps) current.push(item.index)
    else groups.push([item.index])
  }
  return groups
}

export function Wordmark({
  revealed = WORDMARK_GLYPH_COUNT,
  className,
}: {
  revealed?: number
  className?: string
}) {
  const refs = useRef<Array<SVGPathElement | null>>([])
  const [glyphs, setGlyphs] = useState(WORDMARK_GLYPHS_FALLBACK)

  useLayoutEffect(() => {
    const boxes = refs.current.map((path) => {
      if (!path) return { x: 0, width: 0 }
      const box = path.getBBox()
      return { x: box.x, width: box.width }
    })
    if (boxes.some((box) => box.width <= 0)) return
    const next = groupWordmarkGlyphs(boxes)
    if (next.length === WORDMARK_GLYPH_COUNT) setGlyphs(next)
  }, [])

  const visible = new Set<number>()
  glyphs.forEach((group, index) => {
    if (index < revealed) group.forEach((pathIndex) => visible.add(pathIndex))
  })

  return (
    <svg
      viewBox={`0 0 ${WORDMARK_VIEWBOX_WIDTH} ${WORDMARK_VIEWBOX_HEIGHT}`}
      fill="currentColor"
      aria-hidden="true"
      className={cn('block h-7 w-auto max-w-none', className)}
    >
      {WORDMARK_PATHS.map((d, index) => (
        <path
          key={index}
          ref={(path) => {
            refs.current[index] = path
          }}
          d={d}
          opacity={visible.has(index) ? 1 : 0}
        />
      ))}
    </svg>
  )
}
